# Добавляет единый заголовочный блок с указанием лицензии и Credits
# в файлы исходного кода HumanGram-Proxy, где он ещё отсутствует.
# Блок вставляется в самое начало файла с пустой строкой после него,
# чтобы комментарий непосредственно над `package` сохранял роль
# документации пакета.
$ErrorActionPreference = 'Stop'
$root = 'G:\HumanGram\proxy'

$header = @'
// HumanGram-Proxy — локальный прокси MTProto-over-WebSocket.
//
// Лицензия: MIT. Copyright (c) 2026 HumanGram contributors.
//
// Credits:
//   - Flowseal, проект tg-ws-proxy (https://github.com/Flowseal/tg-ws-proxy,
//     MIT) — источник сведений о протоколе локального прокси MTProto,
//     переносящего трафик в WebSocket.
//   - Разработчики Telegram (https://core.telegram.org/mtproto) — протокол
//     MTProto и исходный код клиентов, на совместимость с которыми
//     ориентирована реализация.
//
// Полный текст Credits приведён в LICENSE и README.md.

'@

$changed = 0
Get-ChildItem $root -Recurse -Filter '*.go' | ForEach-Object {
    $text = Get-Content $_.FullName -Raw
    if ($text -match 'Copyright \(c\) 2026 HumanGram contributors') { return }
    # Пропускаем сгенерированный заголовок cgo, он и так помечен.
    if ($text -match 'Code generated by cmd/cgo') { return }
    $updated = $header + "`r`n" + $text
    [System.IO.File]::WriteAllText($_.FullName, $updated, (New-Object System.Text.UTF8Encoding($false)))
    $changed++
    Write-Host ("добавлен заголовок: {0}" -f $_.FullName.Replace("$root\", ''))
}
Write-Host ""
Write-Host ("Обновлено файлов: {0}" -f $changed)
